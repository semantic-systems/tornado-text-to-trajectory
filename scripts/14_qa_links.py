"""Stage 14 — score the annotations and decide which links get published.

Runs in whichever state the project is in:

* **before annotation** — reports what the linker produced (coverage, score
  distribution, which evidence fired) and states plainly that no precision figure
  exists yet, so the report cannot be mistaken for a validated result.
* **after annotation** — joins the labels to the withheld keys and reports
  precision per score band with Wilson intervals, recall from the article-level
  sample, and Cohen's κ from the repeated subset. The publishable threshold is
  read off the per-band table rather than chosen.

    python scripts/14_qa_links.py
"""

from __future__ import annotations

import argparse
import json

import _bootstrap  # noqa: F401

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from tornado_dataset import config, viz
from tornado_dataset.dat.evaluate import wilson_interval
from tornado_dataset.ids import write_manifest

plt.rcParams.update(viz.matplotlib_style())
L = viz.LIGHT
# A label counts as a correct link when the annotator agreed the article really
# refers to that event; whether we called it describes or mentions is scored
# separately, because those are two different kinds of mistake.
POSITIVE = {"describes", "mentions"}
PRECISION_BAR = 0.90


def cohens_kappa(first: list[str], second: list[str]) -> float | None:
    """Agreement beyond chance on the repeated subset."""
    pairs = [(a, b) for a, b in zip(first, second) if a and b]
    if not pairs:
        return None
    labels = sorted({x for pair in pairs for x in pair})
    n = len(pairs)
    observed = sum(1 for a, b in pairs if a == b) / n
    expected = sum((sum(1 for a, _ in pairs if a == label) / n)
                   * (sum(1 for _, b in pairs if b == label) / n) for label in labels)
    return None if expected >= 1 else round((observed - expected) / (1 - expected), 4)


def row_count(path) -> int:
    return len(pd.read_csv(path)) if path.exists() else 0


def main() -> None:
    default_tag = f"{config.WINDOW_START.isoformat()}_{config.WINDOW_END.isoformat()}"
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tag", default=default_tag)
    args = parser.parse_args()

    annotation_dir = config.OUTPUT_DIR / "annotation"
    links = pd.read_csv(config.PROCESSED_DIR / f"article_links_{args.tag}.csv")
    lexis = links[links.corpus == "lexisnexis"]
    manifest = json.loads(
        (config.PROCESSED_DIR / f"manifest_article_links_{args.tag}.json").read_text())
    counts = manifest["counts"]

    sheet_path = annotation_dir / "precision_sheet.csv"
    key_path = annotation_dir / "precision_key.csv"
    labelled = pd.DataFrame()
    if sheet_path.exists() and key_path.exists():
        sheet = pd.read_csv(sheet_path)
        if "label" in sheet and sheet.label.notna().any():
            labelled = sheet[sheet.label.notna()
                             & (sheet.label.astype(str).str.strip() != "")].merge(
                pd.read_csv(key_path), on="pair_id", how="left")

    figures = config.OUTPUT_DIR / "figures"
    figures.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Article → event links — quality report",
        "",
        "Generated by `scripts/14_qa_links.py`.",
        "",
        "## 1. What the linker produced",
        "",
        "| | value |",
        "|---|---|",
        f"| LexisNexis articles | {counts['lexis_articles']} |",
        f"| …with at least one candidate link | {counts['lexis_articles_with_a_link']} "
        f"({counts['lexis_articles_with_a_link'] / max(1, counts['lexis_articles']):.1%}) |",
        f"| mean candidate episodes per article (date window) | "
        f"{counts['lexis_mean_candidate_episodes']} |",
        f"| candidate links written | {counts['lexis_links']} |",
        f"| reached only via the retrospective date pass | {counts['from_retrospective_pass']} |",
        f"| GDELT articles scored | {counts['gdelt_articles']} |",
        "",
        f"Relations: `{counts['by_relation']}` · levels: `{counts['by_level']}`",
        "",
        "The date window alone leaves roughly 25 candidate episodes per article, so the "
        "toponym and corroboration scores are what decide. The window is a cheap "
        "shortlist, not an answer.",
        "",
        "### Which evidence actually fires",
        "",
        "| signal | pairs where it was available | of those, agreeing |",
        "|---|---|---|",
    ]
    for column, label in (("sig_ef_match", "EF rating stated and comparable"),
                          ("sig_fatalities_match", "fatality count stated"),
                          ("sig_date_match", "a date in the text resolved"),
                          ("sig_source_locality", "outlet's own state known")):
        if column in lexis:
            available = int(lexis[column].notna().sum())
            agreeing = int(lexis[column].fillna(False).astype(bool).sum())
            lines.append(f"| {label} | {available} | {agreeing} |")

    if labelled.empty:
        lines += [
            "",
            "## 2. Validation — NOT YET DONE",
            "",
            "**No precision or recall figure exists for these links.** The sheets are "
            "drawn and waiting in `outputs/annotation/`; the rules are in "
            "`docs/annotation_codebook.md`. Until they come back labelled, everything in "
            "`article_links_*.csv` is a **candidate**: nothing should be published as a "
            "link or used as ground truth.",
            "",
            f"Awaiting: {row_count(sheet_path)} precision pairs, "
            f"{row_count(annotation_dir / 'recall_sheet.csv')} recall articles, "
            f"{row_count(annotation_dir / 'agreement_sheet.csv')} repeated pairs for κ.",
            "",
        ]
        print("no labels found yet — wrote the pre-validation report")
    else:
        labelled["correct"] = labelled.label.isin(POSITIVE)
        by_band = labelled.groupby("score_band").agg(
            pairs=("correct", "size"), correct=("correct", "sum"))
        by_band["precision"] = by_band.correct / by_band.pairs
        by_band[["ci_low", "ci_high"]] = [
            wilson_interval(int(row.correct), int(row.pairs)) for row in by_band.itertuples()]
        publishable = by_band[by_band.precision >= PRECISION_BAR]

        strict = labelled[labelled.label.isin(POSITIVE)]
        relation_ok = (strict.label == strict.link_relation).mean() if len(strict) else float("nan")

        lines += [
            "",
            "## 2. Precision, by score band",
            "",
            by_band.reset_index().to_markdown(index=False, floatfmt=".3f"),
            "",
            f"Bands at or above the {PRECISION_BAR:.0%} bar: "
            f"**{', '.join(publishable.index) if len(publishable) else 'none'}**. "
            "Links in lower bands stay in the candidate file.",
            "",
            f"Where the annotator agreed the article refers to the event, the pipeline's "
            f"own `describes` / `mentions` call matched theirs **{relation_ok:.1%}** of "
            f"the time (n={len(strict)}).",
            "",
            "### Label mix",
            "",
            labelled.label.value_counts().rename_axis("label").reset_index(
                name="pairs").to_markdown(index=False),
            "",
        ]

        fig, ax = plt.subplots(figsize=(6.4, 3.4))
        centres = list(range(len(by_band)))
        ax.errorbar(centres, by_band.precision,
                    yerr=[by_band.precision - by_band.ci_low,
                          by_band.ci_high - by_band.precision],
                    fmt="o-", color=L["series1"], capsize=3)
        ax.axhline(PRECISION_BAR, color=L["series2"], lw=1.2)
        ax.annotate(f" publish bar {PRECISION_BAR:.0%}", (0, PRECISION_BAR),
                    color=L["series2"], fontsize=9, va="bottom")
        ax.set_xticks(centres)
        ax.set_xticklabels(by_band.index, rotation=20)
        ax.set_ylim(0, 1.02)
        ax.set_ylabel("annotated precision")
        ax.set_title("Link precision by score band")
        ax.grid(axis="x", visible=False)
        fig.savefig(figures / "link_precision.png")
        plt.close(fig)

        recall_sheet = annotation_dir / "recall_sheet.csv"
        if recall_sheet.exists():
            recall = pd.read_csv(recall_sheet)
            answered = recall[recall.true_event_date.notna()
                              & (recall.true_event_date.astype(str).str.strip() != "")]
            if len(answered):
                key = pd.read_csv(annotation_dir / "recall_key.csv")
                answered = answered.merge(key, on="article_id", how="left")
                found = []
                for row in answered.itertuples():
                    candidates = lexis[lexis.textref_uid == row.textref_uid]
                    stated = str(row.true_event_date)[:7]
                    found.append(any(str(d)[:7] == stated for d in candidates.event_day))
                hits = sum(found)
                low, high = wilson_interval(hits, len(found))
                lines += [
                    "## 3. Recall, from the article-level sample",
                    "",
                    f"Articles where you identified an event from the text: "
                    f"{len(answered)}. The pipeline proposed that event (matched to the "
                    f"month) for **{hits}** of them — recall **{hits / len(found):.1%}** "
                    f"[{low:.1%}, {high:.1%}].",
                    "",
                ]

        agreement_sheet = annotation_dir / "agreement_sheet.csv"
        if agreement_sheet.exists():
            repeat = pd.read_csv(agreement_sheet)
            if "label" in repeat and repeat.label.notna().any():
                mapping = pd.read_csv(annotation_dir / "agreement_key.csv")
                joined = (repeat.rename(columns={"pair_id": "agreement_id",
                                                 "label": "label_second"})
                          .merge(mapping, on="agreement_id")
                          .merge(labelled[["pair_id", "label"]],
                                 left_on="original_pair_id", right_on="pair_id"))
                kappa = cohens_kappa(joined.label.tolist(), joined.label_second.tolist())
                lines += [
                    "## 4. Annotator agreement",
                    "",
                    f"Cohen's κ on {len(joined)} repeated pairs: **{kappa}**. A precision "
                    "figure without this rests on one unexamined judgement.",
                    "",
                ]
        print(f"scored {len(labelled)} labelled pairs; "
              f"bands above the bar: {list(publishable.index)}")

    lines += [
        "## Limitations",
        "",
        "1. **Linking is a measurement.** Even in a band measured at 0.95, one link in "
        "twenty is wrong; downstream work should carry `link_score` rather than treat "
        "links as facts.",
        "2. **The corpus is one LexisNexis query's complete export** — 22,896 unique "
        "articles, not truncated — so recall is conditional on what that query "
        "covered, not on a retrieval cap.",
        "3. **News coverage is itself biased** towards deadly, photogenic and urban "
        "tornadoes; the linked subset inherits that, and it has to be stated wherever "
        "text→geometry results are reported.",
        "4. **GDELT links are weaker by construction**: headline only, no body. Their "
        "precision is reported separately and must not be pooled with LexisNexis.",
    ]

    report_path = config.OUTPUT_DIR / "link_qa_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    write_manifest(config.PROCESSED_DIR / f"manifest_link_qa_{args.tag}.json",
                   "14_qa_links",
                   counts={"labelled_pairs": len(labelled),
                           "validated": bool(len(labelled)),
                           "precision_bar": PRECISION_BAR},
                   outputs=[report_path])
    print(f"wrote {report_path}")


if __name__ == "__main__":
    main()
